"""End-to-end checks of the whole backend flow, from login to an encrypted command.

`esp32_decrypt` below is deliberately written with a plain AES-GCM library and the
documented format only (no app code). It is exactly what the future ESP32 will do,
so a pass here proves the payload can be consumed by an independent implementation.
"""

import base64
import json
import time

import pytest
from Crypto.Cipher import AES

# The documented additional authenticated data. Written out literally on purpose:
# if the backend changes it without updating the docs, these tests fail.
DOCUMENTED_AAD = b"smart-home-command-v1"

ALL_COMMANDS = [
    ("light", "LIGHT_ON", "on"),
    ("light", "LIGHT_OFF", "off"),
    ("fan", "FAN_ON", "on"),
    ("fan", "FAN_OFF", "off"),
    ("door", "DOOR_OPEN", "open"),
    ("door", "DOOR_CLOSE", "closed"),
    ("pump", "PUMP_ON", "on"),
    ("pump", "PUMP_OFF", "off"),
]


def esp32_decrypt(payload, key, aad=DOCUMENTED_AAD):
    """What the ESP32 will do. Raises ValueError if the payload must be rejected."""
    assert payload["algorithm"] == "AES-256-GCM"
    nonce = base64.b64decode(payload["nonce"], validate=True)
    ciphertext = base64.b64decode(payload["ciphertext"], validate=True)
    tag = base64.b64decode(payload["tag"], validate=True)
    assert len(nonce) == 12 and len(tag) == 16

    cipher = AES.new(key, AES.MODE_GCM, nonce=nonce, mac_len=16)
    cipher.update(aad)
    return json.loads(cipher.decrypt_and_verify(ciphertext, tag))


def login(client, credentials, who="admin"):
    username, password = credentials[who]
    response = client.post(
        "/api/auth/login", json={"username": username, "password": password}
    )
    assert response.status_code == 200
    token = response.get_json()["access_token"]
    return {"Authorization": f"Bearer {token}"}


def devices(client, headers):
    response = client.get("/api/status", headers=headers)
    assert response.status_code == 200
    return {name: info["state"] for name, info in response.get_json()["devices"].items()}


@pytest.fixture
def aes_key(app):
    return bytes.fromhex(app.config["AES_SECRET_KEY"])


# --- The main story: tap "LIGHT ON" ------------------------------------------

def test_light_on_from_login_to_decrypted_command(anonymous_client, credentials, aes_key):
    client = anonymous_client

    # 1. Sign in
    headers = login(client, credentials)

    # 2. The dashboard loads the current state
    assert devices(client, headers) == {
        "light": "off",
        "fan": "off",
        "door": "closed",
        "pump": "off",
    }

    # 3. The user taps LIGHT ON
    before = int(time.time())
    response = client.post(
        "/api/commands", json={"device": "light", "command": "LIGHT_ON"}, headers=headers
    )
    after = int(time.time())
    body = response.get_json()

    assert response.status_code == 200
    assert set(body) == {"success", "command_id", "device", "encrypted_payload"}
    assert body["success"] is True and body["device"] == "light"

    # 4. The "ESP32" decrypts it with nothing but the shared key and the documented format
    command = esp32_decrypt(body["encrypted_payload"], aes_key)
    assert set(command) == {"command", "command_id", "device", "timestamp"}
    assert command["command"] == "LIGHT_ON"
    assert command["device"] == "light"
    assert command["command_id"] == body["command_id"]
    assert before - 1 <= command["timestamp"] <= after + 1  # generated by the server

    # 5. The backend state shows the effect
    assert devices(client, headers)["light"] == "on"


@pytest.mark.parametrize("device,command,state", ALL_COMMANDS)
def test_every_command_round_trips(anonymous_client, credentials, aes_key, device, command, state):
    headers = login(anonymous_client, credentials)
    response = anonymous_client.post(
        "/api/commands", json={"device": device, "command": command}, headers=headers
    )
    assert response.status_code == 200

    decrypted = esp32_decrypt(response.get_json()["encrypted_payload"], aes_key)
    assert (decrypted["device"], decrypted["command"]) == (device, command)
    assert devices(anonymous_client, headers)[device] == state


# --- What an attacker or a faulty device must NOT be able to do --------------

def test_receiver_rejects_tampered_wrong_key_and_wrong_context(client, aes_key):
    body = client.post(
        "/api/commands", json={"device": "door", "command": "DOOR_OPEN"}
    ).get_json()
    payload = body["encrypted_payload"]
    assert esp32_decrypt(payload, aes_key)["command"] == "DOOR_OPEN"  # sanity

    for field in ("ciphertext", "tag", "nonce"):
        raw = bytearray(base64.b64decode(payload[field]))
        raw[0] ^= 0x01
        tampered = {**payload, field: base64.b64encode(bytes(raw)).decode()}
        with pytest.raises(ValueError):
            esp32_decrypt(tampered, aes_key)

    with pytest.raises(ValueError):
        esp32_decrypt(payload, bytes(32))  # wrong key
    with pytest.raises(ValueError):
        esp32_decrypt(payload, aes_key, aad=b"another-protocol")  # wrong context


def test_identical_commands_never_produce_identical_messages(client, aes_key):
    first = client.post("/api/commands", json={"device": "fan", "command": "FAN_ON"}).get_json()
    second = client.post("/api/commands", json={"device": "fan", "command": "FAN_ON"}).get_json()

    assert first["command_id"] != second["command_id"]
    assert first["encrypted_payload"]["nonce"] != second["encrypted_payload"]["nonce"]
    assert first["encrypted_payload"]["ciphertext"] != second["encrypted_payload"]["ciphertext"]

    one = esp32_decrypt(first["encrypted_payload"], aes_key)
    two = esp32_decrypt(second["encrypted_payload"], aes_key)
    assert one["command_id"] != two["command_id"]  # lets a receiver spot replays
    assert one["timestamp"] <= two["timestamp"]


def test_no_secret_or_plaintext_ever_appears_in_responses(app, anonymous_client, credentials):
    secrets_to_hide = [
        app.config["AES_SECRET_KEY"],
        app.config["JWT_SECRET_KEY"],
        credentials["admin"][1],
        credentials["viewer"][1],
        "pbkdf2:sha256",
    ]

    login_response = anonymous_client.post(
        "/api/auth/login",
        json={"username": credentials["admin"][0], "password": credentials["admin"][1]},
    )
    headers = {"Authorization": f"Bearer {login_response.get_json()['access_token']}"}
    responses = [
        login_response,
        anonymous_client.get("/api/status", headers=headers),
        anonymous_client.post(
            "/api/commands", json={"device": "light", "command": "LIGHT_ON"}, headers=headers
        ),
        anonymous_client.post("/api/commands", json={"device": "light", "command": "NOPE"}, headers=headers),
        anonymous_client.get("/api/status"),  # 401
        anonymous_client.get("/api/missing"),  # 404
        anonymous_client.post("/api/health"),  # 405
    ]
    for response in responses:
        text = response.get_data(as_text=True)
        for secret in secrets_to_hide:
            assert secret not in text

    # The encrypted command response must not contain the command in clear text.
    command_text = responses[2].get_data(as_text=True)
    assert "LIGHT_ON" not in command_text
    assert "timestamp" not in command_text


def test_viewer_and_anonymous_users_get_no_payload_and_change_nothing(
    anonymous_client, credentials
):
    admin = login(anonymous_client, credentials, "admin")
    viewer = login(anonymous_client, credentials, "viewer")
    before = devices(anonymous_client, admin)

    for headers, expected in ((viewer, 403), (None, 401)):
        response = anonymous_client.post(
            "/api/commands",
            json={"device": "pump", "command": "PUMP_ON"},
            headers=headers or {},
        )
        assert response.status_code == expected
        assert response.get_json()["success"] is False
        assert "encrypted_payload" not in response.get_json()

    assert devices(anonymous_client, admin) == before


def test_invalid_commands_return_no_payload_and_change_nothing(client):
    before = client.get("/api/status").get_json()["devices"]

    for body in (
        {"device": "light", "command": "FAN_ON"},
        {"device": "toaster", "command": "LIGHT_ON"},
        {"device": "light", "command": "LIGHT_DIM"},
        {"device": "light"},
        {},
    ):
        response = client.post("/api/commands", json=body)
        assert response.status_code == 400
        assert response.get_json()["success"] is False
        assert "encrypted_payload" not in response.get_json()

    assert client.get("/api/status").get_json()["devices"] == before


# --- Several users, one house -------------------------------------------------

def test_viewer_sees_what_the_admin_changed(anonymous_client, credentials):
    admin = login(anonymous_client, credentials, "admin")
    viewer = login(anonymous_client, credentials, "viewer")

    assert devices(anonymous_client, viewer)["door"] == "closed"
    anonymous_client.post(
        "/api/commands", json={"device": "door", "command": "DOOR_OPEN"}, headers=admin
    )
    assert devices(anonymous_client, viewer)["door"] == "open"


def test_a_sequence_of_commands_ends_in_the_expected_state(anonymous_client, credentials, aes_key):
    headers = login(anonymous_client, credentials)
    sequence = [
        ("light", "LIGHT_ON"),
        ("fan", "FAN_ON"),
        ("light", "LIGHT_OFF"),
        ("door", "DOOR_OPEN"),
        ("pump", "PUMP_ON"),
        ("pump", "PUMP_OFF"),
    ]
    seen_ids = set()
    for device, command in sequence:
        body = anonymous_client.post(
            "/api/commands", json={"device": device, "command": command}, headers=headers
        ).get_json()
        decrypted = esp32_decrypt(body["encrypted_payload"], aes_key)
        assert (decrypted["device"], decrypted["command"]) == (device, command)
        seen_ids.add(decrypted["command_id"])

    assert len(seen_ids) == len(sequence)
    assert devices(anonymous_client, headers) == {
        "light": "off",
        "fan": "on",
        "door": "open",
        "pump": "off",
    }